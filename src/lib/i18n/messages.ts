export const MESSAGE_CATALOGS: Record<Locale, MessageCatalog> = {
  en: EN_MESSAGES,
  "zh-CN": ZH_CN_MESSAGES,
};

function interpolate(template: string, values: TranslationValues | undefined) {
  if (!values) return template;

  return template.replace(/\{(\w+)\}/g, (match, key: string) => {
    const value = values[key];
    return value === undefined ? match : String(value);
  });
}

export function translate(
  locale: Locale,
  key: MessageKey,
  values?: TranslationValues,
) {
  return interpolate(MESSAGE_CATALOGS[locale][key], values);
}

export function validateMessageCatalogs(
  catalogs: Record<Locale, Record<string, string>>,
) {
  const expected = Object.keys(catalogs.en).sort();
  const problems: string[] = [];

  for (const locale of Object.keys(catalogs) as Locale[]) {
    const actual = Object.keys(catalogs[locale]).sort();
    const missing = expected.filter((key) => !actual.includes(key));
    const extra = actual.filter((key) => !expected.includes(key));
    if (missing.length || extra.length) {
      problems.push(`${locale}: missing [${missing.join(", ")}]; extra [${extra.join(", ")}]`);
    }
  }

  return problems;
}
